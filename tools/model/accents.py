"""regenerates src/Fetchle.Core/Embedding/AccentTable.cs.

string.Normalize is a silent no-op under InvariantGlobalization, so fetchle carries its own strip-accents
table for the ranges below. each entry is what NFD followed by dropping non-spacing marks leaves of a char,
the same thing HF's BertNormalizer does when strip_accents is on.

usage: uv run python -I tools/model/accents.py
"""
import unicodedata
from pathlib import Path

# latin-1 supplement through latin extended-b, greek and coptic through cyrillic, latin extended additional
RANGES = [(0x00C0, 0x024F), (0x0370, 0x04FF), (0x1E00, 0x1EFF)]
OUT = Path(__file__).resolve().parents[2] / "src/Fetchle.Core/Embedding/AccentTable.cs"


def stripped(cp: int) -> str:
    ch = chr(cp)
    if unicodedata.category(ch) == "Mn":
        return ch  # marks are dropped at runtime by category, the table keeps them as they are
    base = "".join(c for c in unicodedata.normalize("NFD", ch) if unicodedata.category(c) != "Mn")
    return base if len(base) == 1 else ch


def literal(start: int, end: int) -> str:
    chars = [stripped(cp) for cp in range(start, end + 1)]
    return "".join(f"\\u{ord(c):04X}" for c in chars)


def main() -> None:
    lines = [
        "namespace Fetchle.Core.Embedding;",
        "",
        "// generated by tools/model/accents.py, do not edit. char at (cp - start) is what cp becomes once its accents are stripped",
        "static partial class Accents",
        "{",
    ]
    for i, (start, end) in enumerate(RANGES):
        lines.append(f"    const char START_{i} = '\\u{start:04X}';")
        lines.append(f'    const string RANGE_{i} = "{literal(start, end)}";')
    lines.append("")
    lines.append("    static char Table(char c)")
    lines.append("    {")
    for i, (start, end) in enumerate(RANGES):
        lines.append(f"        if (c >= START_{i} && c < START_{i} + RANGE_{i}.Length)")
        lines.append("        {")
        lines.append(f"            return RANGE_{i}[c - START_{i}];")
        lines.append("        }")
        lines.append("")
    lines.append("        return c;")
    lines.append("    }")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


main()
